def table(headers, rows, widths=None):
    cols = widths or ['auto'] * len(headers)
    colgroup = '<colgroup>' + ''.join('<col style="width:%s">' % w for w in cols) + '</colgroup>'
    th = ''.join('<th>%s</th>' % x for x in headers)
    trs = ''.join('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>' for r in rows)
    return '<table>%s<thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (colgroup, th, trs)



def find_edge():
    for p in (r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe',
              r'C:\Program Files\Microsoft\Edge\Application\msedge.exe'):
        if os.path.exists(p):
            return p
    return ''


def html_to_pdf(html_path, pdf_path):
    edge = find_edge()
    if not edge:
        return False, '找不到 Edge'
    prof = tempfile.mkdtemp(prefix='edgepdf_')
    cmd = [edge, '--headless=new', '--disable-gpu', '--no-first-run',
           '--user-data-dir=' + prof, '--no-pdf-header-footer',
           '--print-to-pdf=' + pdf_path,
           'file:///' + html_path.replace('\\', '/')]
    try:
        subprocess.run(cmd, capture_output=True, timeout=180)
    except Exception as e:                                   # noqa: BLE001
        return False, str(e)
    return os.path.exists(pdf_path), ''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--no-pdf', action='store_true')
    a = ap.parse_args()

    outdir = os.path.join(ROOT, 'publish', 'srcreg')
    os.makedirs(outdir, exist_ok=True)

    html = ('<!DOCTYPE html><html><head><meta charset="utf-8">'
            '<title>%s %s 软件说明书</title><style>%s</style></head><body>%s</body></html>'
            % (SOFT_NAME, SOFT_VER, CSS, build()))

    html_path = os.path.join(outdir, 'manual.html')
    with io.open(html_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(html)
    print('HTML：%s（%.1f KB）' % (html_path, len(html.encode('utf-8')) / 1024.0))

    if a.no_pdf:
        return 0

    pdf_path = os.path.join(outdir, '说明书_%s_%s.pdf' % (SOFT_NAME, SOFT_VER))
    ok, err = html_to_pdf(html_path, pdf_path)
    if ok:
        print('PDF ：%s（%.1f KB）' % (pdf_path, os.path.getsize(pdf_path) / 1024.0))
    else:
        print('[WARN] 转 PDF 失败：%s' % err)
        print('       可手动用浏览器打开 HTML，Ctrl+P 另存为 PDF')
    return 0


if __name__ == '__main__':
    sys.exit(main())
